local PROPERTIES = T{ [3] = WEAPON_SKILLS, [4] = BLUE_MAGIC, [11] = MOB_SKILLS, [13] = BLOOD_PACTS };

function skillchains.name(element)
    return NAMES[element];
end

function skillchains.level(element)
    return LEVELS[element];
end

function skillchains.properties(category, id)
    local book = PROPERTIES[category];
    return book and book[id] or nil;
end

function skillchains.form(held, used)
    for _, resonance in ipairs(held) do
        local links = LINKS[resonance];
        if (links) then
            for _, property in ipairs(used) do
                if (links[property]) then
                    return links[property];
                end
            end
        end
    end
    return nil;
end

function skillchains.closed(message, held, used)
    local element = MESSAGES[message];
    if (not element) then
        return nil;
    end
    local exact = held and used and skillchains.form(held, used);
    if (exact and NAMES[exact] == NAMES[element]) then
        return exact;
    end
    return element;
end

function skillchains.continues(element)
    return LINKS[element] ~= nil;
end

function skillchains.options(held, known)
    local list = T{};
    for id, used in pairs(WEAPON_SKILLS) do
        local element = skillchains.form(held, used);
        if (element and known(id)) then
            list:append(T{ id = id, element = element, level = LEVELS[element] });
        end
    end
    table.sort(list, function (a, b)
        if (a.level == b.level) then
            return a.id > b.id;
        end
        return a.level > b.level;
    end);
    return list;
end

return skillchains;
